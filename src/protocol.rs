#[derive(Debug, PartialEq)]
pub enum FrameType {
    Text = 0x01,
    Image = 0x02,
}

#[derive(Debug, PartialEq)]
pub struct ClipboardFrame {
    pub frame_type: FrameType,
    pub length: u32,
    pub payload: Vec<u8>,
}

#[derive(Debug, PartialEq)]
pub enum ProtocolError {
    IncompleteHeader,
    UnknownFrameType,
    IncompletePayload,
}

pub fn encode_frame(frame_type: FrameType, payload: &[u8]) -> Vec<u8> {
    let length = payload.len() as u32;

    let mut buffer = Vec::with_capacity(5 + payload.len());
    buffer.push(frame_type as u8);
    buffer.extend_from_slice(&length.to_be_bytes());
    buffer.extend_from_slice(payload);

    buffer
}

pub fn decode_frame(data: &[u8]) -> Result<ClipboardFrame, ProtocolError> {
    if data.len() < 5 {
        return Err(ProtocolError::IncompleteHeader);
    }

    let type_byte = data[0];
    let frame_type = match type_byte {
        0x01 => FrameType::Text,
        0x02 => FrameType::Image,
        _ => return Err(ProtocolError::UnknownFrameType),
    };

    let mut len_bytes = [0u8; 4];
    len_bytes.copy_from_slice(&data[1..5]);

    let length = u32::from_be_bytes(len_bytes);

    if data.len() < 5 + length as usize {
        return Err(ProtocolError::IncompletePayload);
    }

    let payload = data[5..5 + length as usize].to_vec();

    Ok(ClipboardFrame {
        frame_type,
        length,
        payload,
    })
}

