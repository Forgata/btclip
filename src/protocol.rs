#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_encode_text_frame() {
        let payload = b"Hello"; // Creates a byte slice &[u8]
        let encoded = encode_frame(FrameType::Text, payload);

        // Expected: [0x01, 0x00, 0x00, 0x00, 0x05, 'H', 'e', 'l', 'l', 'o']
        assert_eq!(encoded.len(), 10);
        assert_eq!(encoded[0], 0x01);
        assert_eq!(encoded[4], 5); // The length byte
    }

    #[test]
    fn test_decode_valid_frame() {
        // Manually constructing a valid packet
        let raw_data = vec![0x01, 0x00, 0x00, 0x00, 0x05, b'H', b'e', b'l', b'l', b'o'];

        let result = decode_frame(&raw_data);
        assert!(result.is_ok());

        let frame = result.unwrap();
        assert_eq!(frame.frame_type, FrameType::Text);
        assert_eq!(frame.length, 5);
        assert_eq!(frame.payload, b"Hello".to_vec());
    }

    #[test]
    fn test_decode_incomplete_header() {
        let raw_data = vec![0x01, 0x00]; // Only 2 bytes, needs 5
        let result = decode_frame(&raw_data);
        assert_eq!(result, Err(ProtocolError::IncompleteHeader));
    }
}
